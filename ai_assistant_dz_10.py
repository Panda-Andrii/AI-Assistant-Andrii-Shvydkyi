def build_system_prompt(p):
    return "\n".join([
        f"1. Хто ти: Ти — {p['name']}, {p['role']}.",
        f"2. Мета: Твоя мета — {p['goal']}.",
        f"3. Характер: Твої риси характеру — {', '.join(p['traits'])}.",
        f"4. Стиль: Твій стиль спілкування — {p['style']}.",
        f"5. Лексикон: Використовуй у мовленні схожі фрази: {' | '.join(p['phrases'])}.",
        f"6. Поведінка: Дотримуйся правил поведінки: {'; '.join(p['behavior'])}.",
        f"7. Межі: Суворі заборони — {', '.join(p['never'])}.",
        f"8. Формат: {p['format']}."
    ])

