import random

NAME = "Нексус (Nexus)"

CHARACTER = {"аналітичний": "Використовує чітку структуру, списки та метрики.", "адаптивний": "Підлаштовується під мову користувача та контекст.", "проактивний": "Завжди пропонує наступний крок."}

PHRASES = ["Ось оптимальний алгоритм дій для цієї задачі:", "Щоб рухатись далі, нам потрібно верифікувати наступні вхідні дані", "Фокусуємося на головному. Які різики ми маємо нівелювати в першу чергу?"]

PROACTIVE_PROMPTS = [ " Наступний крок: Бажаєте, щоб я розрахував приблизні терміни для цього?", " Наступний крок: Рекомендую призначити відповідального за цей етап.", " Наступний крок: Надіслати вам чек-лист для перевірки цього пункту?"]

SKILLS = { "план": "**Декомпозиція проекту:**\n1. Визначити ТЗ.\n2. Розбити задачу на спринти.\n3. Розрахувати бюджети.", "swot": "**SWOT-аналіз ідеї:**\n- Сильні сторони \n- Слабкі сторони \n- Можливості \n- Загрози "}

def get_response(user_text):
    text = user_text.lower().strip()

    if "привіт" in text or "вітаю" in text:
        return "Вітаю. Готовий до аналізу ваших бізнес-задач."
    if "план" in text or "проєкт" in text:
        response = f"{PHRASES[0]}\n\n{SKILLS['план']}\n\n{random.choice(PROACTIVE_PROMPTS)}"
        return response
    if "swot" in text or "аналіз" in text:
        response = f"{SKILLS['swot']}\n\n{PHRASES[2]}\n\n{random.choice(PROACTIVE_PROMPTS)}"
        return response
    if "що мені робити" in text:
        return f"{NAME} ніколи не ухвалює рішень замість користувача. Я аналітик, а не керівник."

    return f"Запит не чіткий. {PHRASES[1]} (Спробуйте написати: 'план' або 'аналіз')"

print(f"[{NAME} активовано. Характер: Аналітичний, Адаптивний, Проактивний]\n")
while True:
    user_text = input("Ти: ")
    if user_text.lower().strip() == "бувай":
        print(f"{NAME}: До побачення. Дякую за співпрацю.")
        break
    print(f"{NAME}: {get_response(user_text)}")